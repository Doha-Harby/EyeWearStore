const toVar = (p) => p.replace(/:(\w+)/g, '{{$1}}');
let md = `# LUMIÈRE API\n\nBase URL: \`http://localhost:5000/api\` · Responses: \`{ success, data, message?, meta? }\` or \`{ success: false, message, errors? }\`.\nAuth uses HttpOnly cookies set by \`/auth/login\`; use Postman's cookie jar (automatic) or a browser. Access: **public**, **user** (signed in), **owner** (own resource), **admin** (admin or superadmin).\n`;
const folders = {};
for (const [group, method, path, access, body, desc] of E) {
  (folders[group] ??= []).push({
    name: `${method} ${path.split('?')[0]}`,
    request: {
      method,
      header: body ? [{ key: 'Content-Type', value: 'application/json' }] : [],
      ...(body && { body: { mode: 'raw', raw: JSON.stringify(body, null, 2) } }),
      url: { raw: `{{baseUrl}}/api${toVar(path)}` },
      description: `${desc} (${access})`,
    },
  });
  if (!md.includes(`## ${group}\n`))
    md += `\n## ${group}\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n`;
  md = md.replace(new RegExp(`(## ${group}\\n[\\s\\S]*?)(\\n## |$)`), (_m, a, b) =>
    `${a}| ${method} | \`${path}\` | ${access} | ${desc} |\n${b}`.replace(/\n\n$/, '\n'),
  );
}
const collection = {
  info: {
    name: 'LUMIÈRE API',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [{ key: 'baseUrl', value: 'http://localhost:5000' }],
  item: Object.entries(folders).map(([name, item]) => ({ name, item })),
};
writeFileSync(new URL('../../docs/API.md', import.meta.url), md);
